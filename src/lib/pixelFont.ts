/** Retourne la liste des pixels allumés [x, y] d'un texte (5×7 par lettre, 1 colonne d'espace). */
export function pixelText(text: string): {
  pixels: [number, number][];
  width: number;
  height: number;
} {
  const chars = text.toUpperCase().split('');
  const pixels: [number, number][] = [];
  chars.forEach((c, ci) => {
    const g = GLYPHS[c];
    if (!g) return;
    for (let i = 0; i < 35; i++)
      if (g[i] === '1') pixels.push([ci * 6 + (i % 5), Math.floor(i / 5)]);
  });
  return { pixels, width: Math.max(0, chars.length * 6 - 1), height: 7 };
}

/** Générateur pseudo-aléatoire déterministe (mulberry32) à partir d'une chaîne. */
export function seededRandom(seed: string): () => number {
  let h = 1779033703 ^ seed.length;
  for (let i = 0; i < seed.length; i++) {
    h = Math.imul(h ^ seed.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
